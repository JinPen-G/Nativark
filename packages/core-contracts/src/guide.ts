/** 从原任务册的快速入口和Agent模板生成随包指南，字段仍以正式合同为唯一来源。 */
import type { z } from "zod";
import { CORE_CONTRACT_VERSION, type CoreManifest, type CoreSourceSchema } from "./manifest";

const taskFile = "docs/平台底座/Core接入/平台Core接入-开发任务.md";
const plain = (text: string) => text.replace(/[<>&]/g, value => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;" })[value]!)
  .replace(/([\\`*_[\]{}|])/g, "\\$1").replace(/[\r\n]+/g, " ");

export function renderCoreGuide(
  manifest: CoreManifest, taskDocument: string, platformSource: z.infer<typeof CoreSourceSchema>
): string {
  const base = `${platformSource.repository.replace(/\.git$/, "")}/blob/${platformSource.commit}/`;
  const taskUrl = `${base}${encodeURI(taskFile)}`;
  const section = (start: string, end: string) => {
    const from = taskDocument.indexOf(start), to = taskDocument.indexOf(end, from + start.length);
    if (from < 0 || to < 0) throw new Error("接入任务册缺少快速指南或Agent模板锚点，不能生成不完整指南");
    return taskDocument.slice(from + start.length, to).trim().replace(/\]\(#([^)]*)\)/g, `](${taskUrl}#$1)`);
  };
  const quick = section('<a id="core-quick-start"></a>', '<a id="core-agent-template"></a>');
  const agent = section('<a id="core-agent-template"></a>', "### 快速路径之外按需查阅");
  return [
    "<!-- Generated by @rental-os/core-contracts; edit the source task/contract, not this file. -->",
    `# ${plain(manifest.name)} · Core 接入指南`,
    `Core \`${manifest.id}\`，实现 \`${manifest.version}\`，生成器合同 \`${CORE_CONTRACT_VERSION}\`。`,
    `本指南来自[固定底座任务册](${taskUrl})和[正式契约](${base}packages/core-contracts/README.md)。Core来源为[固定提交](${manifest.source.repository.replace(/\.git$/, "")}/commit/${manifest.source.commit})。`,
    "## 当前可执行入口",
    "在已准备依赖的底座源码根目录构建合同包，然后检查解包目录。检查只读取文件和合同，不代表授权或业务已运行。",
    "```sh\nnpm run build -w @rental-os/core-contracts\nnode packages/core-contracts/dist/capabilities.js --query CorePage --json\nnode packages/core-contracts/dist/check.js <Core目录> --host <宿主版本JSON> --json\nnode packages/core-contracts/dist/plan-update.js <当前锁JSON> <升级请求JSON> <数据观察JSON> --json\n```",
    "当前发行仍在拆分公共宿主；下列五步保留对应版本任务册的支持状态。注册/授权/真实业务尚未接线的步骤，不能按已有完整SDK执行。",
    quick,
    agent,
    `## 本 Core 的必需与可选入口\n\n服务端入口为 \`${manifest.entries.server}\`。${manifest.entries.admin ? `后台入口为 \`${manifest.entries.admin}\`。` : "本包没有声明后台入口。"}${manifest.entries.ai ? `本包声明AI贡献 \`${manifest.entries.ai}\`，使用仍需发布与当前授权。` : "本包没有AI贡献，Agent不能查询或操作其业务。"}`,
    `对象范围为${manifest.scope.kind === "tenant" ? "租户" : `本Core的 ${plain(manifest.scope.containerType)} 容器`}。业务字段、状态与操作说明见本包README；许可见LICENSE。`,
    "安装、部署注册、租户授权、成员分配和业务就绪分别成立。停用保留数据与原收据；重开复用绑定、核对当前权限，不能重放未知原操作。"
  ].join("\n\n") + "\n";
}
