// Development-only browser regression for the three source-verified effects.
async (page) => {
  const checks = [], errors = [], missing = [];
  const check = (name, passed, detail) => {
    checks.push({name,passed:Boolean(passed),detail});
    if (!passed) throw new Error(`${name}: ${JSON.stringify(detail)}`);
  };
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => {if(r.status() >= 400) missing.push(r.url());});
  const scroll = async (top, wait=180) => {
    await page.evaluate(top=>scrollTo({top,behavior:'instant'}),top);
    await page.waitForTimeout(wait);
  };
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:8137/source/');
  await page.waitForTimeout(800);
  const reject = page.locator('[data-cookie-action="reject"]');
  if(await reject.isVisible()) await reject.click();
  await page.mouse.move(1420,100);
  await scroll(180);
  const cover = await page.evaluate(()=>{
    const h=document.querySelector('.hero').getBoundingClientRect();
    const tab=document.querySelector('.hero-tab'), t=tab.getBoundingClientRect();
    const p=document.querySelector('.platform-area').getBoundingClientRect();
    return {heroTop:h.top,tabTop:t.top,covered:t.bottom-p.top,foreground:!!document.elementFromPoint(t.left+20,p.top+3)?.closest('.platform-area')};
  });
  check('Hero moves at 40% of document scroll', Math.abs(cover.heroTop+72)<1,cover);
  check('foreground covers 76px of Hero tabs at 180px',Math.abs(cover.covered-76)<1 && cover.foreground,cover);
  await page.screenshot({path:'output/playwright/scroll-restored-hero-180.png'});
  await scroll(260);
  check('Hero tabs become fully covered',await page.evaluate(()=>document.querySelector('.platform-area').getBoundingClientRect().top<=document.querySelector('.hero-tab').getBoundingClientRect().top));
  await scroll(0);
  check('scrolling back restores Hero to top',await page.locator('.hero').evaluate(e=>Math.abs(e.getBoundingClientRect().top)<1));
  await page.setViewportSize({width:1920,height:1080});
  const quoteTop = await page.locator('.quote-viewport').evaluate(e=>e.getBoundingClientRect().top+scrollY);
  const quoteWidth = ()=>page.locator('.quote-slot[data-quote-relative="0"] .quote-card').evaluate(e=>({x:e.getBoundingClientRect().x,width:e.getBoundingClientRect().width,height:e.getBoundingClientRect().height}));
  await scroll(quoteTop-1080);
  const large=await quoteWidth();
  check('story begins at full-page width minus 48px',Math.abs(large.width-1872)<1 && Math.abs(large.x-24)<1,large);
  await scroll(quoteTop-720);
  const middle=await quoteWidth();
  check('story continuously narrows while scrolling',Math.abs(middle.width-1636)<5 && middle.height===650,middle);
  await page.screenshot({path:'output/playwright/scroll-restored-story-wide.png'});
  await scroll(quoteTop-302);
  const small=await quoteWidth();
  check('story ends centered at 1280px',small.width===1280 && small.x===320 && small.height===650,small);
  await page.screenshot({path:'output/playwright/scroll-restored-story-narrow.png'});
  await scroll(quoteTop-1080);
  check('story spread reverses on upward scroll',(await quoteWidth()).width===1872);
  await scroll(quoteTop-400);
  await page.locator('.quote-next').click();
  await page.waitForTimeout(800);
  check('story carousel next still works',await page.locator('.quote-dots button').nth(1).getAttribute('aria-current')==='true');
  check('story stepping uses baseline not expanded width',Math.abs((await quoteWidth()).x-(1920-(await quoteWidth()).width)/2)<1);
  await page.locator('.quote-dots button').nth(3).click();
  await page.waitForTimeout(800);
  await page.locator('.quote-next').click();
  await page.waitForTimeout(800);
  check('story loop stays centered after wrapping',await page.locator('.quote-dots button').nth(0).getAttribute('aria-current')==='true' && Math.abs((await quoteWidth()).x-(1920-(await quoteWidth()).width)/2)<1);
  const teamsTop=await page.locator('.teams-track').evaluate(e=>e.getBoundingClientRect().top+scrollY);
  await scroll(teamsTop-900,1500);
  const before=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  await scroll(teamsTop-780,70);
  const inFlight=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  await page.waitForTimeout(1500);
  const after=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  check('team rail follows 40% scroll delta',Math.abs(after-before-48)<=1,{before,inFlight,after});
  check('team rail spring has intermediate frames',inFlight>before && inFlight<after,{before,inFlight,after});
  await page.screenshot({path:'output/playwright/scroll-restored-team-drift.png'});
  await scroll(teamsTop-900,1500);
  const reversed=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  check('team rail reverses with upward scroll',Math.abs(reversed-before)<=1,{before,reversed});
  await page.waitForTimeout(800);
  check('team rail stops rather than auto-playing',Math.abs((await page.locator('.teams-track').evaluate(e=>e.scrollLeft))-reversed)<=1);
  await scroll(teamsTop-300,1500);
  const buttonBefore=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  const buttonTarget=await page.locator('.teams-track').evaluate((e,b)=>Math.min(e.scrollWidth-e.clientWidth,b+e.querySelector('.team-card').getBoundingClientRect().width+24),buttonBefore);
  await page.locator('.teams-next').click();
  await scroll(teamsTop-180,1100);
  check('team arrow remains usable after scroll drift',await page.locator('.teams-track').evaluate((e,b)=>e.scrollLeft>b+200,buttonBefore));
  check('manual team control wins over simultaneous page scrolling',Math.abs((await page.locator('.teams-track').evaluate(e=>e.scrollLeft))-buttonTarget)<=2);
  await page.locator('.teams-track').focus();
  const keyBefore=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  await page.keyboard.press('ArrowLeft'); await page.waitForTimeout(900);
  check('team keyboard scrolling still works',await page.locator('.teams-track').evaluate((e,b)=>e.scrollLeft<b-200,keyBefore));
  const dragBefore=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  const rail=await page.locator('.teams-track').boundingBox();
  await page.mouse.move(900,rail.y+80); await page.mouse.down();
  await page.mouse.move(790,rail.y+80,{steps:8});
  check('team mouse dragging remains direct',Math.abs((await page.locator('.teams-track').evaluate(e=>e.scrollLeft))-dragBefore-110)<=2);
  await page.mouse.up(); await page.waitForTimeout(300);
  const dragAfter=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  check('released team drag is not overwritten by old spring',Math.abs(dragAfter-dragBefore-110)<=2);
  await page.mouse.move(1880,100);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForTimeout(150);
  await scroll(180);
  check('reduced motion disables Hero parallax',await page.locator('.hero').evaluate(e=>getComputedStyle(e).transform==='none'));
  await scroll(quoteTop-1080);
  check('reduced motion keeps story at baseline width',(await quoteWidth()).width===1280);
  await scroll(teamsTop-900,200);
  const reducedBefore=await page.locator('.teams-track').evaluate(e=>e.scrollLeft);
  await scroll(teamsTop-780,600);
  check('reduced motion disables team scroll drive',await page.locator('.teams-track').evaluate((e,b)=>e.scrollLeft===b && !e.classList.contains('is-scroll-driven'),reducedBefore));
  await page.emulateMedia({reducedMotion:'no-preference'});
  for(const width of [1920,1440,1200,1024,960,768,599,390,320]){
    await page.setViewportSize({width,height:width<600?844:1000});
    await scroll(0,150);
    check('no horizontal overflow '+width,await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  }
  await page.setViewportSize({width:390,height:844});
  await scroll(180);
  check('mobile Hero parallax remains continuous',await page.locator('.hero').evaluate(e=>Math.abs(e.getBoundingClientRect().top+72)<1));
  await scroll(0);
  await page.getByRole('button',{name:'Open menu',exact:true}).click();
  check('mobile menu remains above Hero cover layers',await page.locator('#mobile-menu').isVisible());
  await page.keyboard.press('Escape');
  await page.screenshot({path:'output/playwright/scroll-restored-mobile-top.png'});
  check('no runtime errors',errors.length===0,errors);
  check('no missing assets',missing.length===0,missing);
  return {checks,errors,missing};
}
