async (page) => {
  const checks = [], errors = [], missing = [];
  const check = (name, passed, detail) => {
    checks.push({name, passed: Boolean(passed), detail});
    if (!passed) throw new Error(`${name}: ${JSON.stringify(detail)}`);
  };
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) missing.push(response.url()); });
  await page.emulateMedia({reducedMotion: 'no-preference'});
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto('http://localhost:8137/source/');
  await page.waitForTimeout(800);
  const banner = page.locator('[data-cookie-action="reject"]');
  if (await banner.isVisible()) await banner.click();
  await page.mouse.move(5, 5);
  const widths = () => page.locator('.product-card').evaluateAll(cards => cards.map(card => card.getBoundingClientRect().width));
  await page.evaluate(() => scrollTo({top: document.querySelector('.product-grid').getBoundingClientRect().top + scrollY, behavior:'instant'}));
  const initial = await widths();
  await page.locator('.experience-card').hover();
  await page.waitForTimeout(100);
  const middle = await widths();
  await page.screenshot({path:'output/playwright/restored-xi-mid.png'});
  await page.waitForTimeout(2000);
  const expanded = await widths();
  check('XI accordion interpolates widths', middle[0] > initial[0] + 20 && middle[0] < expanded[0] - 20, {initial,middle,expanded});
  check('XI final expansion matches 2.7 ratio', Math.abs(expanded[0] / expanded[1] - 2.7) < 0.04, expanded);
  check('XI status name and detail both visible', await page.locator('.experience-card .status-name').evaluate(e => getComputedStyle(e).opacity === '1') && await page.locator('.experience-card .status-detail').evaluate(e => getComputedStyle(e).opacity === '1'));
  check('XI correct 696x376 callout animation', await page.locator('.experience-card .product-hover').evaluate(e => e.getBoundingClientRect().width === 696 && !!e.querySelector('svg')));
  await page.screenshot({path:'output/playwright/restored-hover-xi.png'});
  await page.locator('.property-card').hover();
  await page.waitForTimeout(1300);
  const ri = await widths();
  check('RI accordion transfers expansion', Math.abs(ri[1] / ri[0] - 2.7) < 0.04, ri);
  const property = await page.locator('.property-card').evaluate(e => {
    const image = e.querySelector('.property-image'), lease = e.querySelector('.lease-card');
    return {image: image.getBoundingClientRect().toJSON(), lease:lease.getBoundingClientRect().toJSON(), opacity:getComputedStyle(lease).opacity};
  });
  check('RI image and lease sit side by side', property.lease.x >= property.image.right && property.lease.width === 227 && property.opacity === '1', property);
  check('RI no incorrect XI callout overlay', await page.locator('.property-card .product-hover').count() === 0);
  await page.screenshot({path:'output/playwright/restored-hover-ri.png'});
  check('RI lease retains original 312px height', property.lease.height === 312, property.lease.height);
  // Rapid retargeting must not leave a card stuck at an intermediate width.
  await page.locator('.experience-card').hover(); await page.waitForTimeout(70);
  await page.locator('.property-card').hover(); await page.waitForTimeout(70);
  await page.mouse.move(5, 500); await page.waitForTimeout(1500);
  const reset = await widths();
  check('interrupted spring returns to equal columns', Math.max(...reset) - Math.min(...reset) < 2, reset);
  await page.locator('.quote-dots button').first().click(); await page.waitForTimeout(800);
  await page.locator('.quote-track').scrollIntoViewIfNeeded();
  const dragStart = await page.locator('.quote-track').evaluate(e=>new DOMMatrixReadOnly(getComputedStyle(e).transform).m41);
  const quoteBox = await page.locator('.quote-card').nth(1).boundingBox();
  await page.mouse.move(quoteBox.x+500,quoteBox.y+350); await page.mouse.down();
  await page.mouse.move(quoteBox.x+350,quoteBox.y+350,{steps:5});
  const dragMiddle = await page.locator('.quote-track').evaluate(e=>new DOMMatrixReadOnly(getComputedStyle(e).transform).m41);
  check('story rail follows pointer before release', Math.abs(dragMiddle-dragStart+150)<3, {dragStart,dragMiddle});
  await page.mouse.up(); await page.waitForTimeout(850);
  check('story drag settles on next story', await page.locator('.quote-dots button').nth(1).getAttribute('aria-current')==='true');
  const spinner = page.locator('.products-section .intelligence-dots');
  await spinner.scrollIntoViewIfNeeded();
  const frames = [];
  for (let i=0;i<5;i++) { frames.push(await spinner.textContent()); await page.waitForTimeout(95); }
  check('spinner changes Braille frames rather than rotating', new Set(frames).size >= 3, frames);
  await page.locator('.metric').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(1300);
  await page.locator('.metric').first().click();
  await page.waitForTimeout(230);
  const rolling = await page.locator('.metric').first().evaluate(e => [...e.querySelectorAll('.metric-track')].map(track => ({matrix:getComputedStyle(track).transform, blur:getComputedStyle(track).filter, copies:track.children.length})));
  check('metrics use four clipped repeats', rolling.every(track => track.copies === 4), rolling);
  check('metric replay shows intermediate rolling/blur', rolling.some(track => track.matrix !== 'matrix(1, 0, 0, 1, 0, 0)' && track.blur !== 'blur(0px)'), rolling);
  await page.screenshot({path:'output/playwright/restored-metric-mid.png'});
  await page.waitForTimeout(1800);
  const ended = await page.locator('.metric').first().evaluate(e => [...e.querySelectorAll('.metric-track')].map(track => getComputedStyle(track).transform));
  check('metric rolls to final third repeat', ended.every(matrix => matrix === 'matrix(1, 0, 0, 1, 0, -264)'), ended);
  await page.screenshot({path:'output/playwright/restored-metric-end.png'});
  await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
  await page.locator('#hero-tab-0').click(); await page.mouse.move(1200,400); await page.waitForTimeout(1050);
  await page.evaluate(() => document.querySelector('#hero-tab-1').click());
  await page.waitForTimeout(90);
  const heroMotion = await page.locator('#hero-1').evaluate(e => ({slide:getComputedStyle(e).transform,title:getComputedStyle(e.querySelector('h1')).transform}));
  check('hero slides horizontally while copy follows', heroMotion.slide !== 'none' && heroMotion.title !== 'none', heroMotion);
  await page.screenshot({path:'output/playwright/restored-hero-mid.png'});
  await page.waitForTimeout(1100);
  check('hero transition removes outgoing layer', await page.locator('.hero-slide.is-outgoing').count() === 0);
  await page.evaluate(()=>{document.querySelector('#hero-tab-2').click();document.querySelector('#hero-tab-0').click();document.querySelector('#hero-tab-1').click();});
  await page.waitForTimeout(1100);
  check('rapid hero selections leave only the selected panel', await page.locator('.hero-slide.is-outgoing').count()===0 && await page.locator('.hero-slide.is-active').getAttribute('id')==='hero-1');
  await page.locator('#hero-1 .button.white').hover(); await page.waitForTimeout(400);
  check('hero button original glow restored', await page.locator('#hero-1 .hero-cta-wrap').first().evaluate(e => getComputedStyle(e,'::before').opacity === '1' && getComputedStyle(e,'::before').filter === 'blur(7px)'));
  await page.mouse.move(1200,500);
  await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
  await page.mouse.wheel(0,600); await page.waitForTimeout(60); const wheelEarly = await page.evaluate(() => scrollY);
  await page.waitForTimeout(1600); const wheelLate = await page.evaluate(() => scrollY);
  check('wheel has original damping rather than immediate jump', wheelEarly > 0 && wheelEarly < 500 && Math.abs(wheelLate-600) < 2, {wheelEarly,wheelLate});
  await page.mouse.wheel(0,1000); await page.waitForTimeout(60);
  await page.evaluate(()=>scrollTo({top:2400,behavior:'instant'})); await page.waitForTimeout(700);
  check('programmatic scroll interrupts wheel inertia', await page.evaluate(()=>scrollY===2400));
  await page.setViewportSize({width:390,height:844});
  check('resize clears desktop expansion', await page.locator('.product-grid').evaluate(e=>e.style.gridTemplateColumns === ''));
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'})); await page.waitForTimeout(400);
  await page.getByRole('button',{name:'Open menu',exact:true}).click();
  const menuScrollBefore = await page.evaluate(()=>scrollY);
  await page.mouse.move(200,350); await page.mouse.wheel(0,500); await page.waitForTimeout(500);
  check('mobile menu does not scroll the underlying page', await page.evaluate(()=>scrollY)===menuScrollBefore);
  await page.keyboard.press('Escape');
  await page.screenshot({path:'output/playwright/restored-mobile-hero.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('.metric').first().scrollIntoViewIfNeeded();
  await page.locator('.metric').first().click();
  check('reduced motion stops metric rolling', await page.locator('.metric').first().evaluate(e=>e.getAnimations({subtree:true}).length === 0));
  check('no runtime errors', errors.length===0, errors);
  check('no missing assets', missing.length===0, missing);
  await page.emulateMedia({reducedMotion:'no-preference'});
  return {checks,errors,missing};
}
