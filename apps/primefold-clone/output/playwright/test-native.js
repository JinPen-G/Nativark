async (page) => {
 const checks=[]; const errors=[]; const badRequests=[];
 const check=(name,ok,detail)=>{checks.push({name,passed:Boolean(ok),detail});if(!ok)throw new Error(name+' failed: '+JSON.stringify(detail));};
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)badRequests.push({url:r.url(),status:r.status()});});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://localhost:8137/source/');
 await page.waitForTimeout(800);
 const reject=page.locator('[data-cookie-action="reject"]');
 if(await reject.isVisible())await reject.click();
 await page.getByRole('button',{name:'Products',exact:true}).hover();
 check('desktop dropdown opens',await page.locator('.nav-dropdown').first().evaluate(e=>e.classList.contains('is-open')));
 await page.keyboard.press('Escape');
 check('Escape closes dropdown',await page.locator('.nav-dropdown').first().evaluate(e=>!e.classList.contains('is-open')));
 await page.locator('.property-card').hover();await page.waitForTimeout(800);
 check('product hover retains base image',await page.locator('.property-image').evaluate(e=>getComputedStyle(e).opacity==='1'&&e.naturalWidth>0));
 check('product hover reveals lease card',await page.locator('.lease-card').evaluate(e=>getComputedStyle(e).transform==='matrix(1, 0, 0, 1, 0, 0)'));
 await page.mouse.move(5,5);
 await page.locator('#hero-tab-1').click();
 check('hero tab switches',await page.locator('#hero-1').getAttribute('aria-hidden')==='false');
 await page.locator('#hero-tab-1').focus();
 await page.keyboard.press('ArrowRight');
 check('hero keyboard navigation',await page.locator('#hero-tab-2').getAttribute('aria-selected')==='true');
 await page.mouse.move(1200,400);
 await page.locator('#hero-tab-0').click();
 await page.mouse.move(1200,400);
 await page.waitForTimeout(7300);
 check('hero autoplay advances',await page.locator('#hero-1').getAttribute('aria-hidden')==='false');
 await page.evaluate(()=>scrollTo({top:1000,behavior:'instant'}));
 await page.waitForTimeout(400);
 check('scroll header uses glass',await page.locator('#site-header').evaluate(e=>e.classList.contains('is-scrolled')));
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.waitForTimeout(400);
 check('header returns to transparent',await page.locator('#site-header').evaluate(e=>!e.classList.contains('is-scrolled')));
 await page.locator('.quote-next').click();
 await page.waitForTimeout(800);
 check('story next button',await page.locator('.quote-dots button').nth(1).getAttribute('aria-current')==='true');
 await page.locator('.quote-prev').click();await page.waitForTimeout(800);
 await page.locator('.quote-prev').click();await page.waitForTimeout(800);
 check('story loops backward',await page.locator('.quote-dots button').nth(3).getAttribute('aria-current')==='true');
 await page.locator('.quote-dots button').nth(0).click();
 check('story direct selection',await page.locator('.quote-dots button').nth(0).getAttribute('aria-current')==='true');
 await page.locator('.teams-next').click();await page.waitForTimeout(900);
 check('team carousel advances',await page.locator('.teams-track').evaluate(e=>e.scrollLeft>400));
 await page.locator('#newsletter-email').fill('preview@example.com');
 await page.getByRole('button',{name:'Subscribe',exact:true}).click();
 check('newsletter preview response',await page.locator('#newsletter-message').textContent()==='Preview only — no subscription has been sent.');
 await page.locator('.legal-links [data-cookie-settings]').click();
 check('cookie dialog opens',await page.locator('#cookie-dialog').evaluate(e=>e.open));
 await page.keyboard.press('Escape');
 check('cookie dialog closes',await page.locator('#cookie-dialog').evaluate(e=>!e.open));
 await page.reload(); await page.waitForTimeout(600);
 check('consent persists',!(await page.locator('#cookie-banner').isVisible()));
 const widths=[];
 for(const width of [1920,1440,1200,1024,960,768,599,390,320]){
  await page.setViewportSize({width,height:width<600?844:1000});
  await page.waitForTimeout(150);
  const size=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,headerHeight:document.querySelector('.header-inner').getBoundingClientRect().height}));
  widths.push(size); check('no horizontal overflow '+width,size.scrollWidth===width,size);
 }
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 check('mobile menu opens',await page.locator('#mobile-menu').isVisible());
 await page.keyboard.press('Escape');
 check('mobile menu closes',!(await page.locator('#mobile-menu').isVisible()));
 const metricLayout=await page.locator('.metric').evaluateAll(items=>items.map(e=>({wrap:getComputedStyle(e).whiteSpace,height:e.getBoundingClientRect().height,bodyHeight:e.closest('.outcome-content').querySelector('h3').getBoundingClientRect().height})));
 check('mobile metrics stay on one line',metricLayout.every(e=>e.wrap==='nowrap'&&e.height<=88&&e.bodyHeight>0),metricLayout);
 await page.locator('.hero-next').click();
 check('mobile hero next',await page.locator('#hero-1').getAttribute('aria-hidden')==='false');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.reload();await page.waitForTimeout(800);
 const before=await page.locator('.hero-slide.is-active').getAttribute('id');
 await page.waitForTimeout(7300);
 check('reduced motion disables autoplay',before===await page.locator('.hero-slide.is-active').getAttribute('id'));
 const images=await page.locator('img').evaluateAll(imgs=>imgs.filter(e=>!e.complete||!e.naturalWidth).map(e=>e.src));
 check('all images decode',images.length===0,images);
 check('no runtime exceptions',errors.length===0,errors);
 check('no missing requests',badRequests.length===0,badRequests);
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:1440,height:1000});await page.goto('http://localhost:8137/source/');
 return {checks,widths,errors,badRequests};
}
