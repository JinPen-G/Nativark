-- 运营邀请保存待接受授权和一次性凭证哈希，SMTP 配置及投递复用原租户集成/通知表。
CREATE TABLE `tenant_operator_invitations` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `email` VARCHAR(191) NOT NULL,
  `displayName` VARCHAR(100) NOT NULL,
  `tokenHash` CHAR(64) NOT NULL,
  `idempotencyKey` VARCHAR(128) NOT NULL,
  `requestHash` CHAR(64) NOT NULL,
  `invitedBy` VARCHAR(191) NOT NULL,
  `accessSnapshot` JSON NOT NULL,
  `dispatchId` VARCHAR(191) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'pending',
  `expiresAt` DATETIME(3) NOT NULL,
  `acceptedAt` DATETIME(3) NULL,
  `acceptedUserId` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `tenant_operator_invitations_tokenHash_key` (`tokenHash`),
  UNIQUE INDEX `tenant_operator_invitations_idempotency_key` (`tenantId`, `idempotencyKey`),
  INDEX `tenant_operator_invitations_email_idx` (`tenantId`, `email`, `status`),
  INDEX `tenant_operator_invitations_created_idx` (`tenantId`, `createdAt`),
  CONSTRAINT `tenant_operator_invitations_tenantId_fkey` FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
