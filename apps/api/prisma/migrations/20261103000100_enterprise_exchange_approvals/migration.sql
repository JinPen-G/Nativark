-- Exchange approval grants spending only; no inventory, payment or physical fulfillment.
CREATE TABLE `enterprise_exchange_approvals` (
  `tenantId` VARCHAR(191) NOT NULL,
  `id` VARCHAR(191) NOT NULL,
  `corporateCustomerId` VARCHAR(191) NOT NULL,
  `applicantCustomerId` VARCHAR(191) NOT NULL,
  `workspaceId` VARCHAR(191) NOT NULL,
  `orderId` VARCHAR(191) NOT NULL,
  `expectedOrderUpdatedAt` VARCHAR(40) NOT NULL,
  `requestFingerprint` CHAR(64) NOT NULL,
  `previewFingerprint` CHAR(64) NOT NULL,
  `request` JSON NOT NULL,
  `preview` JSON NOT NULL,
  `basis` JSON NOT NULL,
  `state` VARCHAR(20) NOT NULL DEFAULT 'pending',
  `revision` INTEGER NOT NULL DEFAULT 1,
  `reason` VARCHAR(500) NOT NULL,
  `decisionReason` VARCHAR(500) NULL,
  `expiresAt` DATETIME(3) NOT NULL,
  `approvedBy` VARCHAR(191) NULL,
  `reviewerMembershipId` VARCHAR(191) NULL,
  `reviewerMembershipUpdatedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`tenantId`,`id`),
  INDEX `enterprise_exchange_applicant` (`tenantId`,`applicantCustomerId`,`workspaceId`,`state`),
  INDEX `enterprise_exchange_company` (`tenantId`,`corporateCustomerId`,`workspaceId`,`state`),
  CONSTRAINT `enterprise_exchange_order_fk` FOREIGN KEY (`tenantId`,`workspaceId`,`orderId`) REFERENCES `rental_orders` (`tenantId`,`workspaceId`,`id`) ON DELETE RESTRICT,
  CONSTRAINT `enterprise_exchange_tenant_fk` FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `enterprise_exchange_company_fk` FOREIGN KEY (`tenantId`,`corporateCustomerId`) REFERENCES `customer_profiles` (`tenantId`,`id`) ON DELETE RESTRICT,
  CONSTRAINT `enterprise_exchange_applicant_fk` FOREIGN KEY (`tenantId`,`applicantCustomerId`) REFERENCES `customer_profiles` (`tenantId`,`id`) ON DELETE RESTRICT,
  CONSTRAINT `enterprise_exchange_workspace_fk` FOREIGN KEY (`tenantId`,`workspaceId`) REFERENCES `business_workspaces` (`tenantId`,`id`) ON DELETE RESTRICT
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
