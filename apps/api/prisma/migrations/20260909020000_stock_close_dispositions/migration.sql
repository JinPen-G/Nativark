-- STOCK-CLOSE-01：每批归还后的处置事实，供后续养护工单验收恢复。
CREATE TABLE `rental_stock_dispositions` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `workspaceId` VARCHAR(191) NOT NULL,
  `orderId` VARCHAR(191) NOT NULL,
  `inspectionId` VARCHAR(191) NULL,
  `returnBatchKey` VARCHAR(191) NOT NULL,
  `dedupeKey` VARCHAR(191) NOT NULL,
  `itemGroupId` VARCHAR(191) NOT NULL,
  `locationId` VARCHAR(191) NOT NULL,
  `assetId` VARCHAR(191) NULL,
  `quantity` INTEGER NOT NULL,
  `receivedAt` DATETIME(3) NOT NULL,
  `bufferUntil` DATETIME(3) NOT NULL,
  `status` VARCHAR(20) NOT NULL,
  `blockReason` VARCHAR(500) NULL,
  `restoredQuantity` INTEGER NOT NULL DEFAULT 0,
  `restoredAt` DATETIME(3) NULL,
  `restoredBy` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `rental_stock_disp_batch_resource_key` (`workspaceId`, `dedupeKey`),
  KEY `rental_stock_dispositions_scope_idx` (`tenantId`, `workspaceId`, `itemGroupId`, `locationId`),
  KEY `rental_stock_dispositions_order_idx` (`orderId`),
  CONSTRAINT `rental_stock_dispositions_tenant_fkey` FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `rental_stock_dispositions_workspace_fkey` FOREIGN KEY (`tenantId`, `workspaceId`) REFERENCES `business_workspaces` (`tenantId`, `id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `rental_stock_dispositions_order_fkey` FOREIGN KEY (`orderId`) REFERENCES `rental_orders` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `rental_stock_dispositions_inspection_fkey` FOREIGN KEY (`inspectionId`) REFERENCES `rental_inspection_records` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
