test("migration only creates AI tables and constraints, with no business data rewrite", () => {
  assert.deepEqual([...migration.matchAll(/CREATE TABLE `([^`]+)`/gu)].map(match => match[1]), tables);
  for (const match of migration.matchAll(/ALTER TABLE `([^`]+)`/gu)) assert.ok(tables.includes(match[1]), match[1]);
  assert.doesNotMatch(migration, /\b(?:DROP\s+(?:TABLE|DATABASE)|TRUNCATE|DELETE\s+FROM|INSERT\s+INTO|UPDATE\s+`)/iu);
  assert.doesNotMatch(migration, /ON DELETE (CASCADE|SET NULL)|ON UPDATE CASCADE/iu);
  assert.match(migration, /`scopeKey` VARCHAR\(512\)/u);
  assert.match(migration, /`fencingToken` DECIMAL\(20, 0\)/u);
  assert.match(migration, /`cursor` BIGINT UNSIGNED NOT NULL/u);
  assert.doesNotMatch(migration, /AUTO_INCREMENT/u);
  assert.match(migration, /`eventCursor` BIGINT UNSIGNED NOT NULL DEFAULT 0/u);
  assert.match(migration, /PRIMARY KEY \(`scopeId`, `taskId`, `cursor`\)/u);
  assert.match(migration, /`authorizedAt` DATETIME\(3\) NOT NULL/u);
  assert.match(migration, /`sceneVersion` VARCHAR\(64\) NOT NULL/u);
  assert.match(migration, /`traceId` VARCHAR\(191\) NOT NULL/u);
});

