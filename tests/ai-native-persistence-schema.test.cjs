test("storage scope key is explicit and collision-free even for delimiter-bearing IDs", () => {
  assert.deepEqual(columns({ kind: "platform" }), { kind: "PLATFORM", scopeKey: "platform", tenantId: null, workspaceId: null });
  assert.deepEqual(columns({ kind: "tenant", tenantId: "t1" }), { kind: "TENANT", scopeKey: "tenant:2:t1", tenantId: "t1", workspaceId: null });
  assert.deepEqual(columns(h.scope), { kind: "WORKSPACE", scopeKey: "workspace:11:tenant-test:10:space-test", tenantId: "tenant-test", workspaceId: "space-test" });
  assert.notEqual(columns({ kind: "workspace", tenantId: "a:b", workspaceId: "c" }).scopeKey, columns({ kind: "workspace", tenantId: "a", workspaceId: "b:c" }).scopeKey);
  for (const bad of [{}, { kind: "workspace", tenantId: "t1" }, { kind: "platform", tenantId: "t1" }, { kind: "tenant", tenantId: "" }, { kind: "tenant", tenantId: "x".repeat(192) }, { kind: "tenant", tenantId: "非ASCII" }]) assert.throws(() => columns(bad), /AI_PERSISTENCE_SCOPE_INVALID/u);
  assert.ok(columns({ kind: "workspace", tenantId: "a".repeat(191), workspaceId: "b".repeat(191) }).scopeKey.length <= 512);
});

test("database event cursors reject unsigned-bigint overflow without Number rounding", () => {
  assert.equal(cursor("0"), 0n);
  assert.equal(cursor("9007199254740993"), 9007199254740993n);
  assert.equal(cursor("18446744073709551615"), 18446744073709551615n);
  for (const bad of ["18446744073709551616", "-1", "01", "1.0", "1e3", "", 9007199254740993]) assert.throws(() => cursor(bad), /AI_EVENT_CURSOR_INVALID/u);
});

test("CLI preload actually refuses env reads and sockets before access", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "rental-os-ai-guard-"));
  try {
    const audit = path.join(dir, "audit.log"), envFile = path.join(dir, ".env");
    fs.writeFileSync(audit, ""); fs.writeFileSync(envFile, "SYNTHETIC_ONLY=not-a-real-secret");
    const preload = path.join(__dirname, "fixtures/ai-native/prisma-offline-preload.cjs");
    const env = { AI_OFFLINE_AUDIT: audit, SystemRoot: process.env.SystemRoot, PATH: process.env.PATH };
    const read = spawnSync(process.execPath, ["--require", preload, "-e", "require('node:fs').readFileSync('.env')"], { cwd: dir, env, encoding: "utf8", timeout: 10000 });
    assert.notEqual(read.status, 0); assert.match(read.stderr, /refused env-file-read/u);
    const network = spawnSync(process.execPath, ["--require", preload, "-e", "require('node:net').connect(1, '127.0.0.1')"], { cwd: dir, env, encoding: "utf8", timeout: 10000 });
    assert.notEqual(network.status, 0); assert.match(network.stderr, /refused network/u);
    assert.equal(fs.readFileSync(audit, "utf8"), "env-file-read\nnetwork\n");
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});
