    "FOREIGN KEY (`scopeId`, `scopeKind`) REFERENCES `ai_scopes`(`id`, `kind`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `actorKind`) REFERENCES `ai_tasks`(`scopeId`, `id`, `ownerKind`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `runId`) REFERENCES `ai_runs`(`scopeId`, `taskId`, `id`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `id`, `currentRevision`) REFERENCES `ai_proposal_versions`(`scopeId`, `taskId`, `proposalId`, `revision`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `proposalId`, `proposalRevision`, `payloadHash`) REFERENCES `ai_proposal_versions`(`scopeId`, `taskId`, `proposalId`, `revision`, `payloadHash`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `approvalId`, `proposalId`, `proposalRevision`) REFERENCES `ai_approvals`(`scopeId`, `taskId`, `id`, `proposalId`, `proposalRevision`)",
    "FOREIGN KEY (`scopeId`, `taskId`, `proposalId`, `proposalRevision`, `actionId`, `actionFingerprint`) REFERENCES `ai_proposal_actions`(`scopeId`, `taskId`, `proposalId`, `proposalRevision`, `actionId`, `requestFingerprint`)"
