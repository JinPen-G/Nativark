"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const source = fs.readFileSync(path.join(__dirname, "../apps/admin/src/features/platform/categoryDraftFields.ts"), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const actual = { exports: {} };
new Function("module", "exports", compiled)(actual, actual.exports);
const { CATEGORY_ATTRIBUTE_TYPES, CATEGORY_INSPECTION_TYPES, updateCategoryField, categoryArrayUsesTags } = actual.exports;
assert(CATEGORY_INSPECTION_TYPES.includes("photo"));
assert(CATEGORY_INSPECTION_TYPES.includes("text"));
assert(!CATEGORY_INSPECTION_TYPES.includes("string"));
assert(!CATEGORY_INSPECTION_TYPES.includes("date"));
assert(CATEGORY_ATTRIBUTE_TYPES.includes("date"));
assert(!CATEGORY_ATTRIBUTE_TYPES.includes("photo"));
const original = { code: "condition", type: "select", options: ["good", "bad"], required: true };
assert.deepEqual(updateCategoryField(original, "type", "text", true), { code: "condition", type: "text", required: true });
assert.deepEqual(original.options, ["good", "bad"], "编辑不得改写来源版本字段");
assert.equal(updateCategoryField({ type: "number", usageMetric: true }, "type", "photo", true).usageMetric, undefined);
assert.equal(updateCategoryField({ type: "number", usageMetric: true }, "label", "读数", true).usageMetric, true);
assert.deepEqual(updateCategoryField(original, "label", "状态", false).options, original.options);
for (const values of [[], ["cleaning", "delivery"]]) assert(categoryArrayUsesTags("valueAddedServicePresets", values));
for (const name of ["assetFields", "inspectionFields"]) assert(!categoryArrayUsesTags(name, []));
assert(!categoryArrayUsesTags("assetFields", [{ code: "serialNo" }]));
console.log("category-governance-admin-fields: 类型域、类型切换清理、不可变编辑及空数组控件分类通过");
