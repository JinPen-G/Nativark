"use strict";
const assert = require("node:assert/strict");
const { RENTAL_CATEGORY_DEFINITIONS, RENTAL_CAPABILITY_MODULES } = require("@rental-os/shared");
const { WorkspaceCapabilityService } = require("../apps/api/dist/modules/rental-core/workspace-capability.service.js");
const service = new WorkspaceCapabilityService({});
const target = structuredClone(RENTAL_CATEGORY_DEFINITIONS.find((row) => row.code === "camera"));
target.requiredCapabilities = ["camera_kit_handover"];
const instance = { code: "camera_kit_handover", status: "enabled", implementationVersion: "cam-kit-1.0", config: {} };
const hooks = ["camera_kit_handover@cam-kit-1.0"];
const check = (rows, definition = target, registry) => service.adoptionCompatibility(definition, rows, hooks, registry);
assert.equal(check([instance]).valid, true);
assert.equal(check([{ ...instance, status: "paused" }]).valid, false, "暂停不能满足目标必选能力");
assert.equal(check([{ ...instance, implementationVersion: "missing" }]).valid, false, "明确实现版本必须实际登记");
assert.equal(check([{ ...instance, config: { unregistered: true } }]).valid, false, "复用真实配置校验，不能接受未声明参数");
const noDependency = structuredClone(target);
noDependency.defaultCapabilities = noDependency.defaultCapabilities.filter((code) => code !== "bundle_inventory");
assert.ok(check([instance], noDependency).blockers.some((row) => row.message.includes("bundle_inventory")), "Core 依赖必须由目标明确声明，不能靠旧实例伪造");
assert.equal(check([instance], { ...target, code: "camping" }).valid, false, "跨品类扩展不能沿用");
const registry = structuredClone(RENTAL_CAPABILITY_MODULES);
registry.find((row) => row.code === "camera_kit_handover").conflictsWith = ["pickup"];
assert.ok(check([instance], target, registry).blockers.some((row) => row.message.includes("互斥")));
const oldHook = { ...instance, implementationVersion: "previous" };
assert.equal(service.adoptionCompatibility(target, [oldHook], [...hooks, "camera_kit_handover@previous"]).valid, true, "已登记旧实现可继续执行，不强制升级历史实现");
const before = structuredClone(instance);
check([instance, { code: "usage_reading", status: "enabled", implementationVersion: "legacy", config: { wrong: true } }]);
assert.deepEqual(instance, before, "预览不得变更实例、默认配置或实现版本");
assert.equal(check([instance]).complete, false, "能力局部检查不冒充全环境采用就绪");
console.log("category-adoption-capabilities: 必选/适用/依赖/互斥/真实配置与明确实现版本、Core 遗留实例隔离通过");
